def test_g6_two_repeat_streams_never_progress():
    """Both branches registered at 0 and then only re-sent: the wall clock passes 2000 ms and 3000 ms
    but the source span is 0 for ever, so the alert never leaves CAUTION."""
    s = Live()
    out = [s.tick(0, vision=new(0), telemetry=new(0), pv=H, pt=H).AlertSeverity]
    out += severities(s, [(500 * k, {"vision": repeat(0), "telemetry": repeat(0), "pv": H, "pt": H})
                          for k in range(1, 7)])  # 500 ... 3000 ms, all still fresh
    assert out == ["CAUTION"] * 7
    assert s.state["high_end_us"] == s.state["high_src_us"] == us(0)


def test_g6_a_low_risk_new_branch_does_not_vouch_for_an_old_high_one():
    """Weights 0.1 / 0.9 keep the fused score High (82.0) while vision is Low (10.0): telemetry's
    High sample was registered at 0 and is only re-sent, vision sends new LOW frames. Those frames
    are fresh progress in the source clock but do not SUPPORT High, so nothing advances."""
    s = Live(weight_vision=0.1, weight_telemetry=0.9)
    first = s.tick(0, vision=new(0), telemetry=new(0), pv=L, pt=H)
    assert (first.RiskScore, first.RiskLevel, first.AlertSeverity) == (82.0, "High", "CAUTION")
    out = severities(s, [(ms, {"vision": new(ms), "telemetry": repeat(0), "pv": L, "pt": H})
                         for ms in (500, 1000, 1500, 2000, 2500)])
    assert out == ["CAUTION"] * 5
    assert s.state["high_end_us"] == us(0)  # the Low frames never moved the end


def test_g6_the_low_direction_is_symmetric():
    """A latched alert, weights 0.1 / 0.9: telemetry is Low (registered at 0, re-sent) and vision
    sends new HIGH frames, fused score 18.0 = Low. The High frames do not support Low, so the
    recovery does not advance. Control: once vision sends a NEW Low frame the span is covered."""
    s = Live(weight_vision=0.1, weight_telemetry=0.9, freshness_tolerance_s=30).latched()
    first = s.tick(0, vision=new(0), telemetry=new(0), pv=H, pt=L)
    assert (first.RiskScore, first.RiskLevel, first.AlertSeverity) == (18.0, "Low", "HIGH_ALERT")
    for ms in range(1000, 10_000, 1000):
        assert s.tick(ms, vision=new(ms), telemetry=repeat(0), pv=H, pt=L).AlertSeverity == "HIGH_ALERT"
    assert s.state["low_end_us"] == us(0)
    # Control: vision turns Low and brings a NEW frame acquired 10000 ms after the first Low sample.
    done = s.tick(10_000, vision=new(10_000), telemetry=repeat(0), pv=L, pt=L)
    assert done.AlertSeverity == "NORMAL"



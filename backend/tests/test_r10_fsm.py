"""R10-A (unit level) - the LIVE_MODEL_RUNTIME alert FSM, the NEW-only EMA and the exact-age rule.

These tests drive ``run_inference`` directly with the per-branch observation verdicts that
``routers/windows.py`` hands it (``Observations``): which branch is NEW, which is a REPEAT, and the
CANONICAL acquisition time of each. The classification itself (identity -> NEW / REPEAT / 409) is
tested through the HTTP API in ``test_r10_observations.py``.

Every expectation is a literal worked out by hand and written next to the scenario. Nothing is
generated by the reference simulator of the proposal (``r10_sim_v3.py``), and the 2000 / 10000 ms
thresholds, the 3 s tolerance and the microsecond clock are written out, never imported from the
implementation, so a changed constant cannot drag its own expectation along.

Groups (numbering of the R10 proposal, section 6):
  1  original contract       6  exact FSM           9   EMA
  7  single modality         8  Task 5 clean-up     10  configuration and time

Conventions. ``H`` / ``M`` / ``L`` are single-branch probabilities of 0.9 / 0.45 / 0.1, i.e. scores
of 90.0 / 45.0 / 10.0, and a window with ONE effective branch scores that branch's value alone.
With both branches effective the default weights 0.5 / 0.5 average them. ``ema_alpha`` is 1 unless
a test is about the EMA, which makes the smoothing the identity.
"""
from datetime import datetime, timedelta, timezone

import pytest

from app import inference
from app.inference import Observation, Observations, freshness, run_inference
from app.schemas import RuntimeConfig, WindowInput

T0 = datetime(2025, 1, 1, 12, 0, 0, tzinfo=timezone.utc)  # 2025-01-01T12:00:00Z
T0_US = 1_735_732_800_000_000  # the same instant in microseconds since the epoch, written out
H, M, L = 0.9, 0.45, 0.1
SEGMENT_KEYS = ("high_srv_us", "high_src_us", "high_end_us", "high_contrib",
                "low_srv_us", "low_src_us", "low_end_us", "low_contrib")


def at(ms):
    return T0 + timedelta(milliseconds=ms)


def us(ms):
    """Microseconds since the epoch of ``at(ms)``, from the literal above."""
    return T0_US + round(ms * 1000)


def new(ms):
    return Observation("new", at(ms).isoformat())


def repeat(ms):
    return Observation("repeat", at(ms).isoformat())


class Live:
    """Feeds ``run_inference`` the way the router does in LIVE_MODEL_RUNTIME: one persistent state
    dict, a verdict per branch. A branch is present iff its observation is given."""

    def __init__(self, **config):
        self.state = {}
        self.config = RuntimeConfig(**{"ema_alpha": 1, **config})
        self.window_id = 0

    def tick(self, ms, *, vision=None, telemetry=None, pv=0.0, pt=0.0):
        self.window_id += 1
        window = WindowInput(P_distraction=pv, P_telemetry_anomaly=pt,
                             vision_status="fresh" if vision is not None else "missing",
                             telemetry_status="fresh" if telemetry is not None else "missing")
        return run_inference("s", self.window_id, window, state=self.state, config=self.config,
                             operation_mode="LIVE_MODEL_RUNTIME", now=at(ms),
                             observations=Observations(vision, telemetry))

    def latched(self, severity="HIGH_ALERT"):
        """Start from an already latched severity, as a session that has been alerting."""
        self.state["last_severity"] = severity
        return self


def severities(stream, steps):
    """``steps``: (server ms, kwargs of tick) -> the emitted AlertSeverity of each window."""
    return [stream.tick(ms, **kwargs).AlertSeverity for ms, kwargs in steps]



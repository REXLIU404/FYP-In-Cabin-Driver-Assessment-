        s = Live()
        assert s.tick(0, telemetry=new(0), pt=H).AlertSeverity == "CAUTION"
        assert s.tick(1000, telemetry=new(2500), pt=H).AlertSeverity == "CAUTION"  # span 2500, wall 1000
        assert s.state["high_end_us"] - s.state["high_src_us"] == 2_500_000
        assert s.tick(last_ms, telemetry=repeat(2500), pt=H).AlertSeverity == expected



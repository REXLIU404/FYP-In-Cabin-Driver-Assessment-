def test_g10_a_clock_that_steps_forward_cannot_shorten_the_wall_clock_condition():
    """The source clock jumps 4 s ahead (inside the 5 s future tolerance): the span reaches 4000 ms
    at once, but the server clock has run only 500 ms, so there is no alert until 2000 ms have passed
    since the segment opened. R10 does not synchronise clocks; it does keep this wall-clock bound."""
    s = Live()
    assert s.tick(0, telemetry=new(0), pt=H).AlertSeverity == "CAUTION"
    jumped = s.tick(500, telemetry=new(4500), pt=H)  # acquired 4 s 'in the future'
    assert jumped.AlertSeverity == "CAUTION"
    assert s.state["high_end_us"] - s.state["high_src_us"] == 4_500_000
    assert jumped.provenance["telemetry_age_s"] == 0.0  # a negative age is clipped to 0
    assert s.tick(1999, telemetry=repeat(4500), pt=H).AlertSeverity == "CAUTION"
    assert s.tick(2000, telemetry=repeat(4500), pt=H).AlertSeverity == "HIGH_ALERT"


